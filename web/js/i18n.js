export const LANGS = [
  { code: 'en', label: 'English', speech: 'en-IN' },
  { code: 'hi', label: 'हिन्दी', speech: 'hi-IN' },
  { code: 'ta', label: 'தமிழ்', speech: 'ta-IN' },
];
const dicts = { en, hi, ta };

let lang = 'en';
try {
  const saved = localStorage.getItem('relay.web.lang');
  const nav = (navigator.language || 'en').slice(0, 2);
  lang = dicts[saved] ? saved : dicts[nav] ? nav : 'en';
} catch {}

export const getLang = () => lang;
export function setLang(code) {
  if (!dicts[code]) return;
  lang = code;
  try {
    localStorage.setItem('relay.web.lang', code);
  } catch {}
  document.documentElement.lang = code;
}
export const speechLang = () => LANGS.find((l) => l.code === lang)?.speech ?? 'en-IN';
export const has = (k) => k in en;

export function t(key, vars = {}) {
  const s = dicts[lang][key] ?? en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
}

/** Translate static markup: [data-i18n] → textContent, [data-i18n-html] → innerHTML (trusted strings from this file only). */
export function applyStatic(root = document) {
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
  document.documentElement.lang = lang;
}
